function createMultiTrackSegment(
  id: string,
  startTime: number,
  endTime: number,
  texts: Record<TrackKey, string>
): CaptionSegment {
  const tracks: CaptionSegment['tracks'] = {};
  (Object.keys(texts) as TrackKey[]).forEach((key) => {
    const words = buildWordTimingsClient(texts[key], startTime, endTime);
    tracks[key] = {
      text: words.map((w) => w.word).join(' '),
      words,
    };
  });
  return { id, startTime, endTime, tracks };
}

