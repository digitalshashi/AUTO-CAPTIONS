function createMultiTrackSegment(
  id: string,
  startTime: number,
  endTime: number,
  texts: Partial<Record<TrackKey, string>> & { english: string; tinglish: string }
): CaptionSegment {
  const fullTexts: Record<TrackKey, string> = {
    tinglish: texts.tinglish,
    english: texts.english,
    telugu: texts.telugu || 'మనలో ఒక *వైరాగ్య*',
    hinglish: texts.hinglish || texts.tinglish,
    hindi: texts.hindi || 'हमारे अंदर *वैराग्य*',
    roman_urdu: texts.roman_urdu || 'Yaar main poori raat *SOYA-NAHI*',
    urdu: texts.urdu || 'یار میں پوری رات *سویا* نہیں',
    tanglish: texts.tanglish || texts.tinglish,
    tamil: texts.tamil || 'நம்மிடம் ஒரு *வைராக்கியம்*',
    kanglish: texts.kanglish || texts.tinglish,
    kannada: texts.kannada || 'ನಮ್ಮಲ್ಲಿ ಒಂದು *ವೈರಾಗ್ಯ*',
    manglish: texts.manglish || texts.tinglish,
    malayalam: texts.malayalam || 'നമ്മളിൽ ഒരു *വൈരാഗ്യം*',
    marathi: texts.marathi || texts.hindi || 'आपल्यामध्ये एक *वैराग्य*',
    bengali: texts.bengali || 'আমাদের মধ্যে এক *বৈরাগ্য*',
    gujarati: texts.gujarati || 'આપણામાં એક *વૈરાગ્ય*',
    punjabi: texts.punjabi || 'ਸਾਡੇ ਅੰਦਰ ਇੱਕ *ਵੈਰਾਗ*',
    odia: texts.odia || 'ଆମ ଭିତରେ ଏକ *ବୈରାଗ୍ୟ*',
    sindhi: texts.sindhi || 'اسان جي اندر هڪ *جذبو* آهي',
    nepali: texts.nepali || 'हाम्रो भित्र एउटा *संकल्प* छ',
    assamese: texts.assamese || 'আমাৰ ভিতৰত এক *সংকল্প* আছে',
    kashmiri: texts.kashmiri || 'سٲنِس منٛز چھُ اکھ *جذبہٕ*',
    pashto: texts.pashto || 'زموږ په منځ کې یو *جنون* شته',
  };
  const tracks: CaptionSegment['tracks'] = {};
  (Object.keys(fullTexts) as TrackKey[]).forEach((key) => {
    const words = buildWordTimingsClient(fullTexts[key], startTime, endTime);
    tracks[key] = {
      text: words.map((w) => w.word).join(' '),
      words,
    };
  });
  return { id, startTime, endTime, tracks };
}

