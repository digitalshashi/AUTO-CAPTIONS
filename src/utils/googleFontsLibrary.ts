const loadedFontCache = new Set<string>();

/**
 * Dynamically loads any Google Font stylesheet into <head> and triggers browser font loading
 * so HTML5 Canvas and live DOM previews render the selected font immediately.
 */
export function ensureGoogleFontLoaded(fontFamily: string): void {
  if (!fontFamily || typeof document === 'undefined') return;
  const cleanName = fontFamily.replace(/^['"]|['"]$/g, '').trim();
  if (!cleanName || loadedFontCache.has(cleanName)) return;

  loadedFontCache.add(cleanName);

  const entry = COMPLETE_GOOGLE_FONTS_LIBRARY.find(
    (f) => f.name.toLowerCase() === cleanName.toLowerCase()
  );

  const encodedFamily = cleanName.replace(/\s+/g, '+');
  const linkId = `merupify-gfont-${encodedFamily.toLowerCase()}`;

  if (!document.getElementById(linkId)) {
    const link = document.createElement('link');
    link.id = linkId;
    link.rel = 'stylesheet';
    // Use weight-free query first if singleWeightOnly, plus fallback listener if multi-weight fails
    if (entry?.singleWeightOnly) {
      link.href = `https://fonts.googleapis.com/css2?family=${encodedFamily}&display=swap`;
    } else {
      link.href = `https://fonts.googleapis.com/css2?family=${encodedFamily}:wght@400;600;700;800&display=swap`;
      link.onerror = () => {
        // Fallback to default weight if Google Fonts rejects multi-weight axis for this family
        link.href = `https://fonts.googleapis.com/css2?family=${encodedFamily}&display=swap`;
      };
    }
    document.head.appendChild(link);
  }

  if ('fonts' in document && typeof document.fonts?.load === 'function') {
    document.fonts.load(`700 24px "${cleanName}"`).catch(() => {});
    document.fonts.load(`400 24px "${cleanName}"`).catch(() => {});
  }
}

